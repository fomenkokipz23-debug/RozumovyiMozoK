using UnityEngine;

public class ShopManager : MonoBehaviour
{
    [Header("Налаштування сітки")]
    // Масив трансформів (точок/контейнерів) на UI сітці, куди будуть поміщатися товари
    public Transform[] gridSlots;      
    
    // Префаб картки товару (із заготовленим скриптом ShopItemUI), який ми будемо клонувати
    public ShopItemUI itemPrefab;      

    [Header("Дані пташок")]
    // Масив ScriptableObject-файлів, який містить інформацію про абсолютно всіх пташок у грі
    public BirdData[] allBirds;         

    // Метод Start викликається один раз при ініціалізації сцени магазину
    void Start()
    {
        // Запускаємо метод генерації та заповнення вітрини магазину
        FillShop();
    }

    // Приватний метод, який динамічно створює інтерфейс магазину на основі наявних даних
    void FillShop()
    {
        // Проходимо циклом по всьому масиву даних доступних пташок
        for (int i = 0; i < allBirds.Length; i++)
        {
            // Захист від виходу за межі UI: якщо пташок у базі більше, ніж підготовлених місць (слотів) у сітці,
            // ми примусово перериваємо цикл за допомогою оператора break, щоб уникнути помилки IndexError.
            if (i >= gridSlots.Length) break;

            // Динамічно створюємо (клонуємо) новий UI елемент картки товару з префабу.
            // Метод Instantiate приймає префаб і об'єкт-батька (gridSlots[i]), роблячи нову картку дочірньою до свого слоту.
            ShopItemUI newItem = Instantiate(itemPrefab, gridSlots[i]);
            
            // Отримуємо компонент RectTransform (спеціальний Transform для UI елементів в Unity) 
            // і скидаємо його локальну позицію в нуль (Vector2.zero).
            // Це гарантує, що картка стане ідеально по центру свого батьківського слоту, а не зміститься вбік.
            newItem.GetComponent<RectTransform>().anchoredPosition = Vector2.zero;

            // Викликаємо публічний метод ініціалізації самої картки, передаючи туди
            // ScriptableObject з даними поточної пташки (картинка, назва, вимоги до рекорду).
            newItem.SetupItem(allBirds[i]);
        }
    }
}