using UnityEngine;

public class ObstacleMovement : MonoBehaviour
{
    // Швидкість руху об'єкта (перешкоди) ліворуч (за замовчуванням 5 одиниць в секунду)
    public float speed = 5f; 
    
    // Внутрішня змінна для збереження точної координати лівої межі екрану
    private float leftEdge;

    // Метод Start викликається один раз на самому початку гри для цього об'єкта
    void Start()
    {
        // Динамічно розраховуємо ліву межу екрану у світових координатах Unity.
        // Camera.main.ScreenToWorldPoint(Vector3.zero) переводить піксельну точку лівого нижнього кута екрану (0,0)
        // у метри (одиниці) ігрового простору. 
        // Віднімаємо ще 2 одиниці (- 2f) як запас, щоб об'єкт видалявся не на очах у гравця, а вже повністю за межами видимості.
        leftEdge = Camera.main.ScreenToWorldPoint(Vector3.zero).x - 2f;
    }

    // Метод Update викликається кожного кадру гри
    void Update()
    {
        // Переміщуємо об'єкт ліворуч (Vector3.left) за допомогою додавання до поточної позиції.
        // Множення на Time.deltaTime адаптує рух під реальний час, роблячи його плавним незалежно від FPS.
        transform.position += Vector3.left * speed * Time.deltaTime;

        // Перевіряємо, чи перетнув об'єкт розраховану раніше ліву межу
        if (transform.position.x < leftEdge)
        {
            // Якщо об'єкт вийшов за межі екрану — повністю видаляємо його з гри та очищаємо оперативну пам'ять
            Destroy(gameObject);
        }
    }
}